CREATE TABLE IF NOT EXISTS settings (
  `key` VARCHAR(191) PRIMARY KEY, value LONGTEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS users (
  username VARCHAR(64) PRIMARY KEY, password VARCHAR(255) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS member_accounts (
  username VARCHAR(64) PRIMARY KEY, password VARCHAR(255) NOT NULL,
  active TINYINT NOT NULL DEFAULT 1, permissions VARCHAR(191) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS oauth_clients (
  origin VARCHAR(255) NOT NULL, redirect_uri VARCHAR(512) NOT NULL,
  client_id TEXT NOT NULL, client_secret TEXT NOT NULL,
  PRIMARY KEY(origin, redirect_uri)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS visitors (
  id VARCHAR(191) PRIMARY KEY, current_id VARCHAR(191) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS chats (
  visitor_id VARCHAR(191) NOT NULL, id VARCHAR(191) NOT NULL,
  title TEXT NOT NULL, updated_at BIGINT NOT NULL DEFAULT 0,
  theme_bg VARCHAR(100) NOT NULL DEFAULT '', theme_ink VARCHAR(100) NOT NULL DEFAULT '',
  PRIMARY KEY(visitor_id,id), INDEX idx_chats_updated(updated_at),
  FOREIGN KEY(visitor_id) REFERENCES visitors(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS messages (
  visitor_id VARCHAR(191) NOT NULL, chat_id VARCHAR(191) NOT NULL,
  seq INT NOT NULL, role VARCHAR(20) NOT NULL, content LONGTEXT NOT NULL,
  PRIMARY KEY(visitor_id,chat_id,seq),
  FOREIGN KEY(visitor_id,chat_id) REFERENCES chats(visitor_id,id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS shifts (
  id BIGINT PRIMARY KEY AUTO_INCREMENT, day CHAR(10) NOT NULL,
  start CHAR(5) NOT NULL, end CHAR(5) NOT NULL, location VARCHAR(120) NOT NULL,
  note TEXT NOT NULL, special TINYINT NOT NULL DEFAULT 0, INDEX idx_shifts_day(day,start)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS attendance (
  shift_id BIGINT NOT NULL, name VARCHAR(64) NOT NULL, checked_at VARCHAR(40),
  status_override VARCHAR(16) NOT NULL DEFAULT '',
  PRIMARY KEY(shift_id,name),
  FOREIGN KEY(shift_id) REFERENCES shifts(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS weekly_instances (
  day CHAR(10) NOT NULL, slot INT NOT NULL, shift_id BIGINT NOT NULL UNIQUE,
  PRIMARY KEY(day,slot), FOREIGN KEY(shift_id) REFERENCES shifts(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE IF NOT EXISTS field_duty (
  month CHAR(7) NOT NULL, username VARCHAR(64) NOT NULL, registered_at VARCHAR(40) NOT NULL,
  manual TINYINT NOT NULL DEFAULT 0,
  PRIMARY KEY(month,username)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
